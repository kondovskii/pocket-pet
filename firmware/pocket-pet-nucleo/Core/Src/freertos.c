/**
  * @brief  Function implementing the defaultTask thread.
  * @param  argument: Not used
  * @retval None
  */
/* USER CODE END Header_StartDefaultTask */
void StartDefaultTask(void *argument)
{
  /* USER CODE BEGIN StartDefaultTask */

/* Display init happens here, inside the task that owns the panel, rather
 * than in main(). One task owns the framebuffer, so there is never a
 * question of who is writing to it. */
ssd1306_init();

ssd1306_clear();
ssd1306_draw_string(0, 0, "POCKET PET", SSD1306_PIXEL_ON);
ssd1306_draw_string(0, 10, "v1.0", SSD1306_PIXEL_ON);
ssd1306_draw_rect(0, 24, 128, 20, SSD1306_PIXEL_ON);
ssd1306_draw_line(0, 24, 127, 43, SSD1306_PIXEL_ON);
ssd1306_update_screen();

for(;;)
{
  /* Blink is now the liveness indicator: if the LED stops, the scheduler
   * or this task has stalled. osDelay yields the CPU to other tasks for
   * the duration, unlike HAL_Delay which busy-waits and blocks everything. */
  HAL_GPIO_TogglePin(LD3_GPIO_Port, LD3_Pin);
  osDelay(500);
}
/* USER CODE END StartDefaultTask */
}

